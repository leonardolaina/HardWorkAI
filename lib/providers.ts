function slugifyProvider(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export const DIRECTORY_PROVIDERS: ProviderDefinition[] = DIRECTORY_ENTRIES.map(
  ([name, modelsCount], index) => ({
    id: `${slugifyProvider(name)}-${index}`,
    name,
    modelsCount,
    featured: false,
  })
);

export const ALL_PROVIDERS: ProviderDefinition[] = [
  ...FEATURED_PROVIDERS,
  ...DIRECTORY_PROVIDERS,
];

export function getSelectableModels(provider: ProviderDefinition): string[] {
  if (provider.sampleModels && provider.sampleModels.length > 0) {
    return provider.sampleModels;
  }
  const slug = slugifyProvider(provider.name);
  const count = provider.modelsCount ?? 3;
  if (count === 1) {
    return [`${slug}/default`];
  }
  const base = [`${slug}/chat-latest`, `${slug}/reasoning`, `${slug}/coder`];
  if (count >= 10) {
    base.push(`${slug}/fast-mini`, `${slug}/pro`);
  }
  return base.slice(0, Math.min(count, base.length));
}

