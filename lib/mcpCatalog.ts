import type { McpTransport } from './types';

export type McpNameLanguage = 'en' | 'pt';

export interface McpCatalogItem {
  id: string;
  name: string;
  nameEn: string;
  namePt: string;
  description: string;
  approvedAppsOnly?: boolean;
  defaultEndpoint: string;
  defaultTransport: McpTransport;
  monogram: string;
  logoUrl?: string;
  sampleTools: string[];
}

export interface McpConnectionRecord {
  connectorId: string;
  name: string;
  description: string;
  endpoint: string;
  transport: McpTransport;
  approvedAppsOnly: boolean;
  custom: boolean;
  ownerUid: string;
  accountEmail: string;
  everyoneInOrg: boolean;
  people: string[];
  teams: string[];
  toolsSelection: 'all' | 'picked';
  selectedTools: string[];
  connected: boolean;
}

export function getMcpDisplayName(
  item: Pick<McpCatalogItem, 'name' | 'nameEn' | 'namePt'>,
  lang: McpNameLanguage
): string {
  return lang === 'pt' ? item.namePt || item.name : item.nameEn || item.name;
}

